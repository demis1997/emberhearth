import type { AbilityDef, Keyword, MinionDef, Tribe } from '../engine/types';

function m(partial: {
  id: string;
  name: string;
  tribe: Tribe;
  tier: 1 | 2 | 3 | 4 | 5 | 6;
  attack: number;
  health: number;
  keywords?: Keyword[];
  abilities?: AbilityDef[];
  description: string;
  artPrompt: string;
  rarity?: MinionDef['rarity'];
  goldenAttack?: number;
  goldenHealth?: number;
  goldenDescription?: string;
  goldenAbilities?: AbilityDef[];
}): MinionDef {
  return {
    id: partial.id,
    name: partial.name,
    tribe: partial.tribe,
    tavernTier: partial.tier,
    attack: partial.attack,
    health: partial.health,
    keywords: partial.keywords ?? [],
    abilities: partial.abilities ?? [],
    description: partial.description,
    artPrompt: partial.artPrompt,
    rarity: partial.rarity ?? 'common',
    goldenAttack: partial.goldenAttack ?? partial.attack * 2,
    goldenHealth: partial.goldenHealth ?? partial.health * 2,
    goldenDescription: partial.goldenDescription,
    goldenAbilities: partial.goldenAbilities,
  };
}

