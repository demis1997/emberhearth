export const TOKEN_IDS = new Set(
  MINION_DATABASE.filter((m) => m.id.startsWith('token_')).map((m) => m.id),
);

export function getMinionDef(id: string): MinionDef {
  const def = MINION_DATABASE.find((m) => m.id === id);
  if (!def) throw new Error(`Unknown minion: ${id}`);
  return def;
}

export function getPoolMinions(activeTribes: Tribe[]): MinionDef[] {
  return MINION_DATABASE.filter(
    (m) =>
      !TOKEN_IDS.has(m.id) &&
      (m.tribe === 'neutral' || activeTribes.includes(m.tribe)),
  );
}
